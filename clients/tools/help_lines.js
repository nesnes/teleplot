// The lines of the Help panel written with the client libraries (packages/webapp/components/panel-help.js: `lib`, `py`, `ino` of its
// examples) must give the page what the lines of the text protocol give. Each client's test.sh writes a program of them, one block per
// tile of the Help (node help_lines.js <cpp | py | ino> <program> <folder>), runs it (one file per tile in a folder), and its help.test.js
// compares what the library of the page makes of each file with what it makes of the text lines of the same examples (testHelp).
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

const ROOT = path.join(__dirname, '..', '..');
// {now} in the Help is the time of the page: here the time the program was written, saved in the folder of its files (`now`), so
// that what has no time of its own (dated when the client sends it, or when the page reads the text lines) comes after it on both sides
const nowOf = (folder) => Number(fs.readFileSync(path.join(folder, 'now'), 'utf8'));

function loadHelp() {
    const code = fs.readFileSync(path.join(ROOT, 'packages', 'webapp', 'components', 'panel-help.js'), 'utf8');
    return new Function(code + '\nreturn { HELP_TILES, helpLib, helpFill };')();
}

// Per tile: the examples a device sends that this client has calls for, in order
function tilesOf(lang, now) {
    const { HELP_TILES, helpLib, helpFill } = loadHelp();
    return HELP_TILES.map((tile) => ({
        id: tile.id,
        examples: [...(tile.examples || []), ...(tile.more || [])].filter((e) => e.from != 'page' && helpLib(lang, e) !== null)
            .map((e) => ({ code: helpFill(e.code, now), lib: helpFill(helpLib(lang, e), now), same: e.libSame !== false })),
    })).filter((tile) => tile.examples.length);
}

// The bytes of the pictures the Help's lines name (png, jpg, raw)
function pictures() {
    const { HELP_TILES } = loadHelp();
    const all = HELP_TILES.flatMap((t) => [...(t.examples || []), ...(t.more || [])]);
    const bytes = (prefix) => Buffer.from(all.find((e) => e.code.startsWith(prefix)).code.split(':').pop(), 'base64');
    return { png: bytes('PNG|camera,scene:iVBOR'), jpg: bytes('JPG|camera'), raw: bytes('RAW|depth') };
}

const indent = (code, by) => code.split('\n').map((l) => by + l).join('\n');
// A block of its own for each example, unless it declares what a later one uses (a setting, an action handle)
const keeps = (lib) => /tp\.param\(|goTo =/.test(lib);

function program(lang, now) {
    const tiles = tilesOf(lang, now), pics = pictures();
    if (lang == 'py') {
        const out = ['# Generated by clients/tools/help_lines.js from the Help panel: python3 <this> <folder>', 'import base64, os, sys',
            'sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "python"))', 'from teleplot import Teleplot', '',
            'def resetOdometry():', '    pass', 'def driveTo(target):', '    pass'];
        for (const [name, b] of Object.entries(pics)) out.push(`${name} = base64.b64decode("${b.toString('base64')}")`);
        for (const tile of tiles) {
            out.push('', `def tile_${tile.id}(tp):`);
            for (const e of tile.examples) out.push(indent(e.lib, '    '));
        }
        out.push('', 'for name, fn in list(globals().items()):', '    if name.startswith("tile_"):',
            '        tp = Teleplot(file=os.path.join(sys.argv[1], name[5:] + ".teleplot"), flushInterval=0)', '        fn(tp)', '        tp.poll()', '        tp.close()');
        return out.join('\n') + '\n';
    }
    const array = (name, b) => lang == 'cpp' ? `static const std::vector<std::uint8_t> ${name} = {${Array.from(b).join(',')}};` : `static const uint8_t ${name}[] = {${Array.from(b).join(',')}};`;
    const out = ['// Generated by clients/tools/help_lines.js from the Help panel: <this program> <folder>'];
    if (lang == 'cpp') out.push('#include "../Teleplot.h"', '#include <cmath>', '#include <string>', '#include <vector>');
    else out.push('#include "arduino/Arduino.h"', '#include "Teleplot.h"', '#include <stdio.h>', '#include <string>',
        'TestStream Serial;', 'uint64_t simulatedMicros = 1000;', `static int64_t clockMs = ${now} + 1000; // (a clock that gives dates, so that what has no time of its own comes after {now})`, 'static Teleplot::Time dateClock() { return Teleplot::ms(static_cast<double>(clockMs++)); }', 'uint32_t micros() { return static_cast<uint32_t>(simulatedMicros); }', 'uint32_t millis() { return static_cast<uint32_t>(simulatedMicros / 1000); }');
    out.push('static void resetOdometry() {}', 'static void driveTo(Teleplot::Number2D) {}');
    for (const [name, b] of Object.entries(pics)) out.push(array(name, b));
    for (const tile of tiles) {
        out.push('', `static void tile_${tile.id}(std::string const& folder) {`);
        if (lang == 'cpp') out.push(`    Teleplot tp(Teleplot::Options().file(folder + "/${tile.id}.teleplot").flushInterval(std::chrono::milliseconds(0)));`);
        else out.push('    TestStream out;', '    Teleplot tp(out);', '    tp.clock(dateClock);');
        for (const e of tile.examples) out.push(keeps(e.lib) ? indent(e.lib, '    ') : '    {\n' + indent(e.lib, '        ') + '\n    }');
        out.push('    tp.poll();');
        if (lang == 'ino') out.push('    simulatedMicros += 6000000;', '    tp.poll(); // (what was described after the last line of its telemetry: again after 5 s)');
        if (lang == 'cpp') out.push('    tp.flush();');
        else out.push(`    FILE* file = fopen((folder + "/${tile.id}.teleplot.txt").c_str(), "wb");`, '    fwrite(out.written.data(), 1, out.written.size(), file);', '    fclose(file);');
        out.push('}');
    }
    out.push('', 'int main(int argc, char** argv) {', '    if (argc < 2) { return 1; }', ...tiles.map((t) => `    tile_${t.id}(argv[1]);`), '    return 0;', '}');
    return out.join('\n') + '\n';
}

// ---------------------------------------------------------------- what the page makes of it
const close = (a, b) => typeof a == 'number' && typeof b == 'number' ? (Number.isNaN(a) && Number.isNaN(b)) || Math.abs(a - b) <= 1e-4 * Math.max(1, Math.abs(a)) : undefined;
function same(a, b, where) {
    const c = close(a, b);
    if (c !== undefined) { assert.ok(c, `${where}: ${a} != ${b}`); return; }
    if (a && typeof a == 'object') {
        assert.ok(b && typeof b == 'object', `${where}: ${JSON.stringify(b)} instead of ${JSON.stringify(a)}`);
        for (const key of Object.keys(a)) if (a[key] !== undefined) same(a[key], b[key], `${where}.${key}`);
        return;
    }
    assert.equal(b, a, where);
}
// A telemetry as the Help's lines describe it: its attributes, its kinds of data and their latest sample, its limits, its structure
function summary(U, telem, values) {
    const P = U.protocol, out = { attributes: { ...telem.attributes }, data: {} };
    delete out.attributes[P.TELEM_ATTR_NAME];
    const write = out.attributes[P.TELEM_ATTR_WRITE];
    if (write && write.type === '') out.attributes[P.TELEM_ATTR_WRITE] = { ...write, type: undefined }; // (write alone: the type of its data, which a client names)
    for (const [type, entry] of Object.entries(telem.data)) {
        if (!entry || !entry.timestamps || !entry.timestamps.length) continue;
        if (P.isMetaDataType && P.isMetaDataType(+type)) continue; // (compared below)
        out.data[type] = values ? entry.data.map((channel) => channel[channel.length - 1]) : true;
    }
    out.thresholds = telem.getThresholds().map((t) => ({ name: t.name, operator: t.operator, value: t.value, color: t.color || '' })).sort((a, b) => a.name < b.name ? -1 : 1);
    if (telem.getEnum && telem.getEnum()) out.enum = telem.getEnum().items.map((i) => i.path + '#' + (i.kind || ''));
    if (telem.getEdges && telem.getEdges()) out.edges = telem.getEdges().edges.length;
    return out;
}

function testHelp(test, lang, folder, read) {
    const { loadTeleplot } = require(path.join(ROOT, 'packages', 'teleplot-js', 'tests', 'helpers', 'load'));
    const now = nowOf(folder);
    for (const tile of tilesOf(lang, now)) {
        const values = !['settings', 'actions', 'joystick', 'pose'].includes(tile.id); // (there the page writes: the lines show both sides)
        test(`Help, ${tile.id}: the lines of the client give what its text lines give`, () => {
            const T = loadTeleplot();
            for (const e of tile.examples) if (e.same) T.parseDataText({ data: e.code, timestamp: Date.now() });
            T.__timers.run();
            const { U, problems } = read(path.join(folder, tile.id));
            assert.equal(problems, 0, 'everything the client sent is understood');
            for (const telem of Object.values(T.datastore.telemetries)) {
                const name = telem.attributes[T.protocol.TELEM_ATTR_NAME];
                const mine = U.datastore.findByName(name);
                assert.ok(mine, `telemetry ${name}`);
                same(summary(T, telem, values), summary(U, mine, values), name);
            }
            for (const name of Object.keys(T.dashboards.dashboards || {})) assert.ok(U.dashboards.getDashboard(name), `dashboard ${name}`);
        });
    }
}

module.exports = { testHelp, tilesOf };

if (require.main === module) {
    const [lang, file, folder] = process.argv.slice(2); // node help_lines.js <cpp | py | ino> <program> <folder of its files>
    const now = Date.now();
    fs.mkdirSync(folder, { recursive: true });
    fs.writeFileSync(path.join(folder, 'now'), String(now));
    fs.writeFileSync(file, program(lang, now));
}
